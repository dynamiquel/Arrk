#!/usr/bin/env python3
"""Render shared product guides. No dependencies; paragraphs, headings, lists and inline code.

Run `python3 site/build-guides.py` after editing a module's Documentation/*.md.
CI can use --check to detect stale output. The generated page is checked in so the
existing static Pages upload works even without a build step.
"""

import argparse
import html
from pathlib import Path
import re


SITE = Path(__file__).resolve().parent
SOURCE = SITE.parent / "src"
OUTPUT = SITE / "product-guides.html"


def inline(text):
    """Escape all source HTML; the only inline markup allowed is paired backticks."""
    return "".join(
        f"<code>{html.escape(part)}</code>" if index % 2 else html.escape(part)
        for index, part in enumerate(text.split("`"))
    )


def topic_id(path):
    return path.parent.parent.name.removeprefix("Arrk.").lower() + "-" + path.stem


def render():
    topics = []
    articles = []
    for path in sorted(SOURCE.glob("*/Documentation/*.md"), key=lambda path: path.stem):
        blocks = path.read_text(encoding="utf-8").strip().split("\n\n")
        if not blocks[0].startswith("# "):
            raise ValueError(f"{path}: missing title")
        topic = topic_id(path)
        title = blocks[0][2:]
        topics.append(f'<a href="#{topic}">{html.escape(title)}</a>')
        sections = []
        content = []
        ids = {"overview"}
        for block in blocks[1:]:
            if block.startswith("## "):
                heading = block[3:]
                section = re.sub(r"[^a-z0-9]+", "-", heading.lower()).strip("-")
                if section in ids:
                    raise ValueError(f"{path}: duplicate section id {section}")
                ids.add(section)
                anchor = f"{topic}-{section}"
                sections.append(f'<li><a href="#{anchor}">{html.escape(heading)}</a></li>')
                content.append(f'<h3 id="{anchor}">{inline(heading)}</h3>')
            elif block.startswith("- ") or re.match(r"\d+\. ", block):
                ordered = not block.startswith("- ")
                pattern = r"\d+\. (.+)" if ordered else r"- (.+)"
                items = []
                for line in block.splitlines():
                    match = re.fullmatch(pattern, line)
                    if not match or line.count("`") % 2:
                        raise ValueError(f"{path}: invalid list item {line}")
                    items.append(f"<li>{inline(match[1])}</li>")
                tag = "ol" if ordered else "ul"
                content.append(f"<{tag}>" + "\n".join(items) + f"</{tag}>")
            else:
                if block.startswith(("#", "- ", "```", ">")) or "\n" in block:
                    raise ValueError(f"{path}: unsupported Markdown block; use headings, lists and single-line paragraphs")
                if block.count("`") % 2:
                    raise ValueError(f"{path}: unpaired inline code delimiter")
                content.append(f"<p>{inline(block)}</p>")
        articles.append(
            f'<article class="guide-section" id="{topic}">\n'
            f'<h2>{html.escape(title)}</h2>\n'
            '<nav aria-label="Sections in this topic"><ul>\n'
            + "\n".join(sections) + "\n</ul></nav>\n"
            + "\n".join(content) + "\n</article>"
        )
    if not topics:
        raise ValueError("No product guides found")
    return """<!doctype html>
<!-- Generated by site/build-guides.py from module Documentation/*.md. Do not edit. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="color-scheme" content="dark">
  <title>Product guides — Arrk</title>
  <meta name="description" content="Step-by-step help for setting up Arrk, uploading media, playing music and video, managing downloads and sharing with your household.">
  <link rel="canonical" href="https://dynamiquel.github.io/Arrk/product-guides.html">
  <link rel="icon" href="assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="assets/css/site.css">
</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>
  <header class="site-header"><div class="wrap header-inner">
    <a class="brand" href="index.html"><img src="assets/logo.svg" width="34" height="34" alt=""><span>Arrk</span></a>
    <nav aria-label="Main navigation"><a href="guide.html">Setup guide</a> · <a href="setup.html">Install</a> · <a href="faq.html">FAQ</a></nav>
  </div></header>
  <main id="main" class="product-guides">
    <section class="page-hero"><div class="wrap">
      <h1>Product guides</h1>
      <p class="lead">Set up your library, upload a movie, fix a stuck download or share Arrk with your household. Find the steps you need below.</p>
      <p>New to Arrk? Start with <a href="setup.html">installation</a>, then the <a href="guide.html">setup walkthrough</a>. Already up and running? Pick a topic or use your browser's Find.</p>
      <p>Some settings need an administrator. Keep passwords and API keys private, and back up before changing storage or deleting media.</p>
    </div></section>
    <section class="section section--flush-top"><div class="wrap guide-layout">
      <aside class="guide-sidebar"><h2>Topics</h2><nav class="guide-nav" aria-label="Product guide topics">
""" + "\n".join(topics) + """
      </nav></aside>
      <div class="guide-content">
""" + "\n".join(articles) + """
      </div>
    </div></section>
  </main>
  <footer class="site-footer"><div class="wrap"><p>Arrk · Early alpha — expect changes. <a href="https://github.com/dynamiquel/Arrk">Source and issues</a></p></div></footer>
</body>
</html>
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated output is stale")
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            parser.exit(1, "Product guide page is stale; run python3 site/build-guides.py\n")
        print("Product guide page matches the Markdown source.")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
        print(f"Generated {OUTPUT.relative_to(SITE.parent)}")
