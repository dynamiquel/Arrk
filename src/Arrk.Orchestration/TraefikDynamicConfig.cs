using System.Text;
using Microsoft.Extensions.Configuration;
using Arrk.Core;
using Arrk.Core.Configuration;
using Arrk.Core.Models;
using Arrk.Core.Services;

namespace Arrk.Orchestration;

/// <summary>
/// Writes Traefik's dynamic (file provider) configuration. This is used for routes that
/// cannot be expressed as Docker labels: the Arrk web UI itself (a container Arrk
/// does not create) and services routed through the VPN sidecar (whose ports live in
/// Gluetun's network namespace, so Traefik's Docker provider cannot address them).
/// </summary>
public static class TraefikDynamicConfig
{
    public const string ArrkFileName = "stackarr.yaml";
    public const string VpnFileName = "vpn.yaml";
    public const int UiPort = 5186;

    /// <summary>
    /// Writes every file-provider route Arrk owns: the Arrk UI itself (when proxied) and
    /// the VPN-routed services. Call this whenever the config changes so Traefik picks up route,
    /// proxy and VPN-routing edits immediately.
    /// </summary>
    public static void WriteAllRoutes(
        ArrkConfig config,
        VolumePathResolver volumeResolver,
        ArrkInstance arrk,
        ServiceRegistry registry,
        IConfiguration configuration,
        string? selfContainerName = null)
    {
        WriteArrkUiRoute(config, volumeResolver, arrk, selfContainerName ?? arrk.SelfContainerName);
        WriteVpnRoutes(config, volumeResolver, arrk, registry, configuration);
    }

    /// <summary>
    /// Writes the UI route into the dynamic config directory. When the UI should not be
    /// proxied (or Arrk is not running in a container, so its address is unknown), the
    /// file is removed to avoid a stale route.
    /// </summary>
    public static void WriteArrkUiRoute(
        ArrkConfig config,
        VolumePathResolver volumeResolver,
        ArrkInstance arrk,
        string? selfContainerName)
    {
        string directory = volumeResolver.ResolveToLocalPath(RelativeVolumes.ReverseProxyDynamic);
        Directory.CreateDirectory(directory);
        string path = Path.Combine(directory, ArrkFileName);

        if (!config.Routes.Proxy || string.IsNullOrWhiteSpace(selfContainerName))
        {
            if (File.Exists(path))
                File.Delete(path);
            return;
        }

        string content =
            "# Generated by Arrk. Do not edit by hand.\n" +
            "http:\n" +
            "  routers:\n" +
            "    stackarr:\n" +
            "      rule: \"PathPrefix(`/`)\"\n" +
            "      entryPoints:\n" +
            "        - web\n" +
            "      service: stackarr\n" +
            "      priority: 1\n" +
            "  services:\n" +
            "    stackarr:\n" +
            "      loadBalancer:\n" +
            "        servers:\n" +
            $"          - url: \"http://{selfContainerName}:{UiPort}\"\n";

        File.WriteAllText(path, content);
    }

    /// <summary>
    /// Writes file-provider routers for services that are exposed through the proxy but run
    /// inside the VPN sidecar's network namespace. Their ports are reachable on the Gluetun
    /// container, so each service URL points at Gluetun. The file is removed when no service
    /// is VPN-routed.
    /// </summary>
    public static void WriteVpnRoutes(
        ArrkConfig config,
        VolumePathResolver volumeResolver,
        ArrkInstance arrk,
        ServiceRegistry registry,
        IConfiguration configuration)
    {
        string directory = volumeResolver.ResolveToLocalPath(RelativeVolumes.ReverseProxyDynamic);
        Directory.CreateDirectory(directory);
        string path = Path.Combine(directory, VpnFileName);

        List<(TraefikConfig Traefik, string Host)> routes = [];
        foreach (Service service in registry.GetEnabled(configuration))
        {
            IReadOnlyList<ContainerSpec> specs = service.Definition.BuildContainerSpecs(configuration, volumeResolver, arrk);
            foreach (ContainerSpec spec in specs)
            {
                if (spec.Traefik == null || !ServiceProvisioner.UsesSharedNetwork(spec))
                    continue;

                routes.Add((spec.Traefik, arrk.GetVpnContainerName()));
            }
        }

        if (routes.Count == 0)
        {
            if (File.Exists(path))
                File.Delete(path);
            return;
        }

        StringBuilder sb = new();
        sb.Append("# Generated by Arrk. Do not edit by hand.\n");
        sb.Append("http:\n");
        sb.Append("  routers:\n");
        foreach ((TraefikConfig traefik, string _) in routes)
        {
            sb.Append($"    {traefik.ServiceName}:\n");
            sb.Append($"      rule: \"{traefik.Rule}\"\n");
            sb.Append("      entryPoints:\n");
            sb.Append($"        - {traefik.EntryPoints}\n");
            sb.Append($"      service: {traefik.ServiceName}\n");
            if (BuildMiddlewares(traefik).Count > 0)
                sb.Append($"      middlewares:\n");
            foreach (string middleware in BuildMiddlewares(traefik))
                sb.Append($"        - {middleware}\n");
        }

        HashSet<string> writtenMiddlewares = [];
        foreach ((TraefikConfig traefik, string _) in routes)
        {
            if (!string.IsNullOrWhiteSpace(traefik.StripPrefix))
                writtenMiddlewares.Add($"{traefik.ServiceName}-stripprefix");
        }

        sb.Append("  services:\n");
        foreach ((TraefikConfig traefik, string host) in routes)
        {
            sb.Append($"    {traefik.ServiceName}:\n");
            sb.Append("      loadBalancer:\n");
            sb.Append("        servers:\n");
            sb.Append($"          - url: \"http://{host}:{traefik.Port}\"\n");
        }

        if (writtenMiddlewares.Count > 0)
        {
            sb.Append("  middlewares:\n");
            foreach ((TraefikConfig traefik, string _) in routes)
            {
                if (string.IsNullOrWhiteSpace(traefik.StripPrefix))
                    continue;
                string name = $"{traefik.ServiceName}-stripprefix";
                sb.Append($"    {name}:\n");
                sb.Append("      stripPrefix:\n");
                sb.Append("        prefixes:\n");
                sb.Append($"          - \"{traefik.StripPrefix}\"\n");
            }
        }

        File.WriteAllText(path, sb.ToString());
    }

    static List<string> BuildMiddlewares(TraefikConfig traefik)
    {
        List<string> middlewares = [.. traefik.Middlewares];
        if (!string.IsNullOrWhiteSpace(traefik.StripPrefix))
            middlewares.Insert(0, $"{traefik.ServiceName}-stripprefix");
        return middlewares;
    }
}
